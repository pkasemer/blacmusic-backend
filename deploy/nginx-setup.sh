#!/usr/bin/env bash
# Adds the Blac Music nginx site next to whatever is already served. Run as root on the VPS
# from the directory that holds blacmusic.conf:
#
#   ssh root@HOST 'bash -s' < deploy/nginx-setup.sh      (blacmusic.conf is read from /tmp/blacmusic.conf)
#
# It never edits another site's configuration. nginx is only reloaded after
# `nginx -t` passes, and a failed test removes the new site again.
set -euo pipefail
[ "$(id -u)" = 0 ] || { echo "run as root"; exit 1; }
SRC=/tmp/blacmusic.conf
[ -f "$SRC" ] || { echo "upload deploy/nginx/blacmusic.conf to $SRC first"; exit 1; }

mkdir -p /etc/nginx/blacmusic /var/www/certbot

echo "== Cloudflare address ranges (used to trust CF-Connecting-IP only from Cloudflare)"
tmp=$(mktemp)
for family in ips-v4 ips-v6; do
  curl -fsS --max-time 20 "https://www.cloudflare.com/$family" >> "$tmp"; echo >> "$tmp"
done
{
  echo "# generated by deploy/nginx-setup.sh from https://www.cloudflare.com/ips-v4 and ips-v6"
  grep -E '^[0-9a-fA-F:.]+/[0-9]+$' "$tmp" | sed 's/^/set_real_ip_from /; s/$/;/'
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} > /etc/nginx/blacmusic/cloudflare-realip.conf
rm -f "$tmp"
n=$(grep -c '^set_real_ip_from' /etc/nginx/blacmusic/cloudflare-realip.conf)
[ "$n" -ge 10 ] || { echo "only $n Cloudflare ranges found, refusing to continue"; exit 1; }
echo "$n ranges"

echo "== placeholder certificate (replaced by certbot's real one)"
if [ ! -f /etc/nginx/blacmusic/fullchain.pem ]; then
  openssl req -x509 -nodes -newkey rsa:2048 -days 30 -subj "/CN=blacmusic.pkasemer.com" \
    -keyout /etc/nginx/blacmusic/privkey.pem -out /etc/nginx/blacmusic/fullchain.pem 2>/dev/null
  chmod 600 /etc/nginx/blacmusic/privkey.pem
fi
for f in /etc/letsencrypt/options-ssl-nginx.conf /etc/letsencrypt/ssl-dhparams.pem; do
  [ -f "$f" ] || { echo "missing $f (certbot's nginx defaults)"; exit 1; }
done

echo "== install the site"
cp "$SRC" /etc/nginx/sites-available/blacmusic.conf
ln -sfn /etc/nginx/sites-available/blacmusic.conf /etc/nginx/sites-enabled/blacmusic.conf
if nginx -t 2>&1; then
  systemctl reload nginx
  echo "nginx reloaded"
else
  echo "nginx -t FAILED, removing the new site"
  rm -f /etc/nginx/sites-enabled/blacmusic.conf
  nginx -t 2>&1 | tail -3
  exit 1
fi
